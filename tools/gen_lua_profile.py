"""Generate the loader's Lua fingerprints from the explicitly supported executable.

Uses only Python's standard library. Unknown builds are rejected, not silently trusted.
Run from any directory: python gen_lua_profile.py path/to/stormworks64.exe
"""
import hashlib
import pathlib
import re
import struct
import sys

EXPECTED_SHA256 = "55914301628a31b278ff1d4aa9fd0c0446341759bf72083a8e3aa1dff859e6c3"
ROOT = pathlib.Path(__file__).resolve().parents[1]


def generate(exe):
    data = pathlib.Path(exe).read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise ValueError("Unsupported executable SHA-256; review the engine profile before porting")
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("Not a PE executable")
    machine, section_count = struct.unpack_from("<HH", data, pe + 4)
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    optional = pe + 24
    if machine != 0x8664 or struct.unpack_from("<H", data, optional)[0] != 0x20B:
        raise ValueError("Expected x64 PE32+")
    sections = []
    for i in range(section_count):
        offset = optional + optional_size + i * 40
        virtual_size, rva, raw_size, raw = struct.unpack_from("<IIII", data, offset + 8)
        sections.append((rva, raw_size, raw))

    def at(rva, size):
        for start, length, raw in sections:
            if start <= rva and rva + size <= start + length:
                return data[raw + rva - start:raw + rva - start + size]
        raise ValueError(f"RVA outside file-backed section: {rva:#x}")

    # Mask absolute pointers changed by ASLR (IMAGE_REL_BASED_DIR64).
    reloc_rva, reloc_size = struct.unpack_from("<II", data, optional + 112 + 5 * 8)
    relocation_bytes = set()
    pos = 0
    while pos < reloc_size:
        page, block_size = struct.unpack("<II", at(reloc_rva + pos, 8))
        if block_size < 8 or pos + block_size > reloc_size:
            raise ValueError("Invalid relocation block")
        for offset in range(8, block_size, 2):
            entry = struct.unpack("<H", at(reloc_rva + pos + offset, 2))[0]
            if entry >> 12 == 10:
                relocation_bytes.update(range(page + (entry & 0xFFF), page + (entry & 0xFFF) + 8))
        pos += block_size

    source = (ROOT / "src/native_lua.cpp").read_text(encoding="utf-8")
    rvas = sorted(set(int(v, 16) for v in re.findall(r"g_base\s*\+\s*(0x[0-9a-fA-F]+)", source)))
    lines = ["// Generated by tools/gen_lua_profile.py; supported v1.15.18 x64 only.",
             "#pragma once", "static constexpr LuaFingerprint kLuaFingerprints[] = {"]
    for rva in rvas:
        # Vtable address ranges are validated separately by their slots; their absolute
        # pointers would otherwise be entirely wildcarded.
        if rva >= 0xA92000:
            continue
        blob = at(rva, 32)
        mask = [0 if rva + i in relocation_bytes else 255 for i in range(len(blob))]
        octets = ", ".join(f"0x{x:02x}" for x in blob)
        masks = ", ".join(f"0x{x:02x}" for x in mask)
        lines.append(f"    {{0x{rva:x}, {{{octets}}}, {{{masks}}}}},")
    lines.append("};")
    target = ROOT / "src/lua_profile.generated.h"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {len(lines) - 4} fingerprints: {target}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: gen_lua_profile.py stormworks64.exe")
    generate(sys.argv[1])
