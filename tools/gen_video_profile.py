"""Generate exact native video fingerprints for the reviewed executable only."""
import hashlib
import pathlib
import re
import struct
import sys
from gen_lua_profile import EXPECTED_SHA256, ROOT


def generate(exe):
    data = pathlib.Path(exe).read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise ValueError("Unsupported executable SHA-256; review video hooks before porting")
    pe = struct.unpack_from("<I", data, 0x3c)[0]
    count = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    sections = []
    for i in range(count):
        pos = pe + 24 + opt_size + i * 40
        _, rva, size, raw = struct.unpack_from("<IIII", data, pos + 8)
        sections.append((rva, size, raw))

    def at(rva, size):
        for start, length, raw in sections:
            if start <= rva and rva + size <= start + length:
                return data[raw + rva - start:raw + rva - start + size]
        raise ValueError(f"RVA outside file-backed section: {rva:#x}")

    source = (ROOT / "src/video_profile.h").read_text()
    values = dict((name, int(value, 16)) for name, value in
                  re.findall(r"constexpr uint32_t (\w+) = (0x[0-9a-f]+);", source))
    lines = ["// Generated by tools/gen_video_profile.py, reviewed Stormworks 1.15.18 x64.",
             "#pragma once", "static constexpr Fingerprint kVideoFingerprints[] = {"]
    for name in ("kMonitorDrawCall", "kGpuDrawCall", "kMonitorDraw", "kGpuDraw", "kMonitorDestroy"):
        rva = values[name]
        blob = at(rva, 32)
        # These selected windows have no absolute relocated operands. Assert this assumption.
        reloc_rva, reloc_size = struct.unpack_from("<II", data, pe + 24 + 112 + 5 * 8)
        pos = 0
        while pos < reloc_size:
            page, block = struct.unpack("<II", at(reloc_rva + pos, 8))
            if block < 8 or pos + block > reloc_size:
                raise ValueError("Invalid relocation block")
            for off in range(8, block, 2):
                entry = struct.unpack("<H", at(reloc_rva + pos + off, 2))[0]
                location = page + (entry & 0xfff)
                if entry >> 12 == 10 and location < rva + 32 and location + 8 > rva:
                    raise ValueError(f"Fingerprint {name} contains an ASLR relocation")
            pos += block
        if name.endswith("Call") and blob[0] != 0xe8:
            raise ValueError("Expected CALL rel32")
        if name.endswith("Call"):
            target = rva + 5 + struct.unpack_from("<i", blob, 1)[0]
            expected = values["kMonitorDraw" if name == "kMonitorDrawCall" else "kGpuDraw"]
            if target != expected:
                raise ValueError("Unexpected call target")
        lines.append(f"    {{0x{rva:x}, {{{', '.join(f'0x{x:02x}' for x in blob)}}}}},")
    lines.append("};")
    target = ROOT / "src/video_profile.generated.h"
    target.write_text("\n".join(lines) + "\n")
    print(f"Generated video fingerprints: {target}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: gen_video_profile.py stormworks64.exe")
    generate(sys.argv[1])
