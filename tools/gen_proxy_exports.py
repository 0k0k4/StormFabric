r"""Generate MSVC /export pragmas forwarding every export of a System32 DLL.

Usage: python gen_proxy_exports.py iphlpapi > ../src/proxy_exports.h
Forwarders use the \\.\GLOBALROOT\SystemRoot\System32 path so the loader never
resolves them back to the proxy itself (same technique as mrexodia/perfect-dll-proxy).
"""
import os, sys
import pefile

name = sys.argv[1] if len(sys.argv) > 1 else "iphlpapi"
path = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", name + ".dll")
pe = pefile.PE(path, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
# C string literal for the linker path \\.\GLOBALROOT\SystemRoot\System32\<name>
target = r"\\\\.\\GLOBALROOT\\SystemRoot\\System32\\" + name
print(f"// Generated by tools/gen_proxy_exports.py from {path} -- do not edit.")
print("#pragma once")
for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
    if e.name:
        n = e.name.decode()
        print(f'#pragma comment(linker, "/export:{n}={target}.{n},@{e.ordinal}")')
    else:
        print(f'#pragma comment(linker, "/export:__ord{e.ordinal}={target}.#{e.ordinal},@{e.ordinal},NONAME")')
