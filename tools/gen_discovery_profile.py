"""Convert retained Ghidra evidence into compiled, instruction-bounded contracts.
No user-supplied runtime profile is loaded by the DLL.
"""
import json
import hashlib
import struct
from pathlib import Path
from discovery_contract_merge import merge_contracts

ROOT = Path(__file__).resolve().parents[1]
GROUPS = {"ui": 1, "lua": 2, "qol": 4, "editor": 8, "notifications": 16, "video": 32,
          "custom_display_targets": 64, "custom_display_registration": 128,
          "custom_display_dialog_widgets": 256, "custom_display_vehicle_observer": 512,
          "custom_display_vehicle_activity": 1024, "custom_display_dialog_construction": 2048,
          "custom_display_catalogue_route": 4096, "custom_display_dialog_callbacks": 8192,
          "custom_display_dialog_input": 16384, "custom_display_native_input_state": 32768}

def literal(value):
    return json.dumps(value)

def byte_literal(hex_string):
    # Small tokens avoid MSVC's per-string-literal size limit.
    data = bytes.fromhex(hex_string)
    return "\n".join('"' + ''.join(f'\\x{b:02x}' for b in data[i:i+128]) + '"' for i in range(0, len(data), 128))

data = json.loads((ROOT / "tools/discovery_contracts.json").read_text())
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_runtime_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_dialog_widget_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_vehicle_observer_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_vehicle_activity_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_dialog_construction_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_catalogue_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_dialog_callback_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_dialog_input_contracts.json").read_text()))
data = merge_contracts(data, json.loads((ROOT / "tools/custom_display_native_input_state_contracts.json").read_text()))
assert data["reference_sha256"] == "55914301628a31b278ff1d4aa9fd0c0446341759bf72083a8e3aa1dff859e6c3"
entries = data["entries"] + data["witnesses"]
typed = json.loads((ROOT / "tools/discovery_data_witnesses.json").read_text())
reference = (ROOT.parent / "Stormworks/stormworks64.exe").read_bytes()
assert hashlib.sha256(reference).hexdigest() == typed["reference_sha256"] == data["reference_sha256"]
nt = struct.unpack_from("<I", reference, 0x3c)[0]
count, optional_size = struct.unpack_from("<H", reference, nt+6)[0], struct.unpack_from("<H", reference, nt+20)[0]
sections = []
for i in range(count):
    offset = nt+24+optional_size+i*40
    _, va, raw_size, raw = struct.unpack_from("<IIII", reference, offset+8)
    sections.append((va,raw_size,raw))
def read_rva(rva, size):
    for va,n,raw in sections:
        if va <= rva and rva+size <= va+n:
            return reference[raw+rva-va:raw+rva-va+size]
    raise ValueError("witness table not file-backed")
typed_by_key = {entry["key"]: entry for entry in typed["entries"]}
assert set(typed_by_key) <= {entry["rva"] for entry in entries}
for e in entries:
    witness = typed_by_key.get(e["rva"])
    if not witness:
        continue
    body = bytes.fromhex(e["bytes"])
    mask = bytearray.fromhex(e["mask"])
    base = witness["base_instruction_offset"]
    instruction = bytes.fromhex(witness["base_instruction_hex"])
    assert body[base:base+len(instruction)] == instruction
    assert e["start"]+witness["base_end"]+struct.unpack_from("<i",body,witness["base_operand"])[0] == 0
    for table in witness["tables"]:
        start, instruction = table["instruction_offset"], bytes.fromhex(table["instruction_hex"])
        assert body[start:start+len(instruction)] == instruction
        assert struct.unpack_from("<I",body,table["operand"])[0] == table["rva"]
        assert mask[table["operand"]:table["operand"]+4] == bytes([255])*4
        targets = struct.unpack("<"+"I"*table["count"],read_rva(table["rva"],table["count"]*4))
        table["target_offsets"] = [target-e["start"] for target in targets]
        assert all(0 <= target < len(body) for target in table["target_offsets"])
        mask[table["operand"]:table["operand"]+4] = bytes(4)
    e["mask"] = mask.hex()
lines = ["// Generated by tools/gen_discovery_profile.py from retained Ghidra evidence.", "#pragma once"]
for i, e in enumerate(entries):
    assert len(e["bytes"]) == len(e["mask"]) and e["bytes"]
    for field in ("bytes", "mask"):
        lines.append(f"static const char kDiscovery_{field}_{i}[] =\n{byte_literal(e[field])};")
    if e["refs"]:
        lines.append(f"static constexpr Edge kDiscovery_edges_{i}[] = {{")
        for r in e["refs"]:
            assert 0 <= r["offset"] <= r["end"]-4 < len(e["bytes"])//2
            assert bytes.fromhex(e["mask"])[r["offset"]:r["offset"]+4] == bytes(4)
            lines.append("    {%d,%d,0x%x,%s}," % (r["offset"],r["end"],r["target"],str(r["flow"]).lower()))
        lines.append("};")
    witness = typed_by_key.get(e["rva"])
    if witness:
        for j,table in enumerate(witness["tables"]):
            values=",".join(hex(x) for x in table["target_offsets"])
            lines.append(f"static constexpr uint32_t kDiscovery_table_targets_{i}_{j}[] = {{{values}}};")
        lines.append(f"static const RvaTable kDiscovery_rva_tables_{i}[] = {{")
        for j,table in enumerate(witness["tables"]):
            lines.append(f'    {{{table["operand"]},{witness["base_operand"]},{witness["base_end"]},kDiscovery_table_targets_{i}_{j},{table["count"]}}},')
        lines.append("};")
lines.append("static const Contract kDiscoveryContracts[] = {")
for i,e in enumerate(entries):
    group = sum(GROUPS[g] for g in e["groups"])
    edge = f"kDiscovery_edges_{i}" if e["refs"] else "nullptr"
    witness = typed_by_key.get(e["rva"])
    tables = f'kDiscovery_rva_tables_{i},{len(witness["tables"])}' if witness else 'nullptr,0'
    lines.append(f'    {{0x{e["rva"]:x},0x{e["start"]:x},{len(e["bytes"])//2},{group},{literal(e["name"])},kDiscovery_bytes_{i},kDiscovery_mask_{i},{edge},{len(e["refs"])},{tables} }},')
lines.append("};")
for i,t in enumerate(data["tables"]):
    lines.append(f"static constexpr Slot kDiscovery_slots_{i}[] = {{")
    lines.extend(f'    {{{s["slot"]},0x{s["target"]:x}}},' for s in t["slots"])
    lines.append("};")
lines.append("static const Table kDiscoveryTables[] = {")
for i,t in enumerate(data["tables"]):
    group = sum(GROUPS[g] for g in t.get("groups", [t["group"]]))
    lines.append(f'    {{0x{t["rva"]:x},{group},{literal(t["type"])},kDiscovery_slots_{i},{len(t["slots"])} }},')
lines.append("};")
(ROOT / "src/engine_discovery.generated.h").write_text("\n".join(lines) + "\n")
print(f"Generated {len(data['entries'])} primary contracts, {len(data['witnesses'])} witnesses, {len(data['tables'])} RTTI vtables")
